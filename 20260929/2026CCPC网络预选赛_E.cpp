ull splitmix64(ull x)
{
    x += 0x9e3779b97f4a7c15ULL;
    x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9ULL;
    x = (x ^ (x >> 27)) * 0x94d049bb133111ebULL;
    return x ^ (x >> 31);
}
void moth()
{
    int n;
    cin >> n;
    vector<vector<int>> a(3, vector<int>(n));
    for (int i = 0; i < 3; i++)
    {
        for (int j = 0; j < n; j++) cin >> a[i][j];
    }
    ull p1 = 0, p2 = 0, p3 = 0;
    int ans = 0;
    for (int i = 0; i < n; i++)
    {
        p1 += splitmix64(a[0][i]);
        p2 += splitmix64(a[1][i]);
        p3 += splitmix64(a[2][i]);
        if (p1 == p2 || p2 == p3 || p1 == p3) ans++;
    }
    cout << ans << '\n';
}
