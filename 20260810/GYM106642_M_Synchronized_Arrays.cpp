void moth()
{
    int n;
    cin >> n;
    vector<ll> a(n + 1), b(n + 1);
    for (int i = 1; i <= n; i++) cin >> a[i];
    for (int i = 1; i <= n; i++) cin >> b[i];
    map<ll, ll> mp1, mp2;
    map<pair<ll, ll>, ll> mp3;
    ll ans = 0;
    for (int i = 1; i <= n; i++)
    {
        ll x1 = a[i] + b[i], x2 = a[i] - b[i];
        if (mp1.count(x1)) ans += mp1[x1];
        if (mp2.count(x2)) ans += mp2[x2];
        if (mp3.count({a[i], b[i]})) ans -= mp3[{a[i], b[i]}];
        // cout << ans << '\n';
        mp1[x1]++;
        mp2[x2]++;
        mp3[{a[i], b[i]}]++;
    }
    cout << ans << '\n';
}
int main()
{
    ios::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    int _ = 1;
    cin >> _;
    while (_--) moth();
    return 0;
}